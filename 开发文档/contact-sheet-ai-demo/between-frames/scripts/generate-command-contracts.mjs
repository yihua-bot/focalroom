// M1 命令及请求 DTO 从同一 JSON Schema 生成；--check 检测契约漂移。
import { spawnSync } from 'node:child_process';
import { readFile, writeFile } from 'node:fs/promises';
const schema = JSON.parse(await readFile(new URL('../contracts/gui-command-request.schema.json', import.meta.url), 'utf8'));
const snake = name => name.replace(/[A-Z]/g, letter => `_${letter.toLowerCase()}`);
const tsType = field => {
  if (field.oneOf) return 'DomainCommand';
  if (field.enum) return field.enum.map(value => JSON.stringify(value)).join(' | ');
  if (Array.isArray(field.type)) return field.type.map(type => tsType({ ...field, type })).join(' | ');
  return ({ array: 'string[]', integer: 'number', string: 'string', null: 'null' })[field.type];
};
const rustType = field => {
  if (field.oneOf) return 'GuiCommand';
  if (Array.isArray(field.type)) return `Option<${rustType({ ...field, type: field.type.find(type => type !== 'null') })}>`;
  return ({ array: 'Vec<String>', integer: 'i64', string: 'String' })[field.type];
};
const variants = schema.properties.command.oneOf;
const events = JSON.parse(await readFile(new URL('../contracts/app-events.json', import.meta.url), 'utf8')).events;
const tsCommands = '// Generated by scripts/generate-command-contracts.mjs.\nexport type DomainCommand =\n' + variants.map(variant => '  | { ' + Object.entries(variant.properties).map(([key, field]) => `${key}: ${key === 'type' ? JSON.stringify(field.const) : tsType(field)}`).join('; ') + ' }').join('\n') + ';\n\nexport interface GuiCommandRequest {\n' + Object.entries(schema.properties).map(([key, field]) => `  ${key}: ${tsType(field)};`).join('\n') + '\n}\n';
const rustCommands = '// Generated by scripts/generate-command-contracts.mjs.\nuse serde::{Deserialize, Serialize};\n\n#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]\n#[serde(tag = "type", rename_all_fields = "camelCase", deny_unknown_fields)]\npub enum GuiCommand {\n' + variants.map(variant => {
  const fields = Object.entries(variant.properties).filter(([key]) => key !== 'type');
  return fields.length ? `    ${variant.properties.type.const} {\n${fields.map(([key, field]) => `        ${snake(key)}: ${rustType(field)},`).join('\n')}\n    },` : `    ${variant.properties.type.const} {},`;
}).join('\n') + '\n}\n\n#[derive(Debug,Clone,Serialize,Deserialize)]\n#[serde(rename_all="camelCase",deny_unknown_fields)]\npub struct GuiCommandRequest {\n' + Object.entries(schema.properties).map(([key, field]) => (Array.isArray(field.type) ? '    #[serde(deserialize_with="required_nullable")]\n' : '') + `    pub ${snake(key)}: ${rustType(field)},`).join('\n') + '\n}\n\nfn required_nullable<\'de,D,T>(deserializer:D)->Result<Option<T>,D::Error> where D:serde::Deserializer<\'de>,T:Deserialize<\'de> { Option::<T>::deserialize(deserializer) }\n';
const ts = tsCommands + '\n' + events.map(event => `export const ${event.constant} = ${JSON.stringify(event.transport)};\n`).join('');
const rust = rustCommands + '\n' + events.map(event => `pub const ${event.constant}: &str = ${JSON.stringify(event.transport)};\n`).join('');
const formattedRust = spawnSync('rustfmt', ['--edition', '2024', '--emit', 'stdout'], { input: rust, encoding: 'utf8' });
if (formattedRust.status !== 0) throw new Error(formattedRust.stderr);
for (const [name, content] of [['../src/domain/commands.generated.ts', ts], ['../src-tauri/src/commands_generated.rs', formattedRust.stdout]]) {
  const url = new URL(name, import.meta.url);
  if (process.argv.includes('--check')) {
    if (await readFile(url, 'utf8') !== content) throw new Error(`命令契约漂移：${name}`);
  } else await writeFile(url, content);
}
console.log('M1 command contracts: OK');

// —— Agent 契约静态校验（M5 补）：结构合法性 + 关键约束防误改 ——
const tools = JSON.parse(await readFile(new URL('../contracts/agent-tool-contracts.json', import.meta.url), 'utf8'));
if (!Array.isArray(tools.tools) || tools.tools.length === 0) throw new Error('agent-tool-contracts：tools 非数组或为空');
const names = tools.tools.map(tool => tool.name);
if (new Set(names).size !== names.length) throw new Error('agent-tool-contracts：工具名重复');
const required = ['get_project_context','list_photos','search_photos','inspect_photos','compare_photos','retrieve_preferences','get_sequence','create_selection_draft','update_draft_sequence','evaluate_draft','request_feedback','finish_task'];
for (const name of required) if (!names.includes(name)) throw new Error(`agent-tool-contracts：缺少工具 ${name}`);
for (const tool of tools.tools) {
  if (tool.strict !== true) throw new Error(`工具 ${tool.name} 未启用 strict`);
  if (typeof tool.description !== 'string' || !tool.description) throw new Error(`工具 ${tool.name} 缺少描述`);
  if (tool.access && ['shell','sql','network'].includes(tool.access)) throw new Error(`工具 ${tool.name} 声明了越权访问级别`);
}
const taskSchema = JSON.parse(await readFile(new URL('../contracts/agent-task-request.schema.json', import.meta.url), 'utf8'));
const start = taskSchema.properties.command.oneOf.find(branch => branch.properties?.type?.const === 'StartTask');
if (!start) throw new Error('agent-task-request：缺少 StartTask');
if (!('consentId' in start.properties)) throw new Error('agent-task-request：StartTask 缺少 consentId');
const budget = start.properties.budget;
if (budget.properties.maxCloudImages.maximum !== 100) throw new Error('agent-task-request：云端图像上限应为 100');
console.log('Agent contracts: OK');

// 人工记忆控制只接受明确的项目归属及目标 ID，不能声明权限来源。
const memorySchema = JSON.parse(await readFile(new URL('../contracts/memory-command-request.schema.json', import.meta.url), 'utf8'));
const memoryVariants = memorySchema.properties.command.oneOf;
const memoryNames = ['SetEvidenceExcluded', 'ConfirmHypothesis', 'RetireHypothesis', 'RestoreHypothesis', 'CorrectHypothesis', 'SetHypothesisEnabled', 'DeleteHypothesis', 'DeleteEvidence', 'PurgeObservationCache'];
if (memorySchema.additionalProperties !== false || memoryVariants.length !== memoryNames.length) throw new Error('memory-command-request：请求结构漂移');
for (const name of memoryNames) {
  const branch = memoryVariants.find(item => item.properties?.type?.const === name);
  if (!branch || branch.additionalProperties !== false || Object.keys(branch.properties).some(key => !branch.required.includes(key))) throw new Error('memory-command-request：缺少严格命令 ' + name);
  const id = branch.properties.evidenceId ?? branch.properties.hypothesisId;
  if (id && (id.type !== 'integer' || id.minimum !== 1)) throw new Error('memory-command-request：ID 边界漂移');
}
console.log('Memory contracts: OK');
