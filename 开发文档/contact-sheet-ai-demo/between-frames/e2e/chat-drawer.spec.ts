import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const evidence = resolve('../docs/evidence/ux-chat-drawer-2026-10-20');
test('访客打开 Focal AI 解释登录原因，取消后保留选区与焦点，不增加 AI 导航', async ({ page }) => {
 await page.goto('/');
 const nav = page.getByRole('navigation', { name: '未命名的日常' });
 await expect(nav).toBeVisible();
 await expect(nav.getByRole('button', { name: 'Focal AI' })).toHaveCount(0);
 const photo = page.getByRole('button', { name: '查看第 2 张 交错的视线', exact: true });
 await photo.click();
 const tile = page.getByTestId('photo-2');
 await expect(tile).toHaveClass(/selected/);
 const open = page.getByRole('main').getByRole('button', { name: 'Focal AI' });
 await open.click();
 const login = page.getByRole('dialog', { name: '登录 FocalRoom' });
 await expect(login).toContainText('登录后即可使用 Focal AI，查看可用额度并管理订阅。');
 await expect(login).toContainText('登录不会自动上传照片。');
 await expect(page.getByRole('dialog', { name: 'Focal AI', exact: true })).toHaveCount(0);
 await login.getByRole('button', { name: '暂不登录' }).click();
 await expect(login).toHaveCount(0);
 await expect(open).toBeFocused();
 await expect(tile).toHaveClass(/selected/);
 await photo.click(); await page.keyboard.press('k');
 await expect(tile).toHaveClass(/keep/);
});
