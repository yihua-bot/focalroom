import { test, expect } from '@playwright/test';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
const evidence = resolve('../docs/evidence/ux-chat-drawer-2026-10-20');
test('工作台对话抽屉保留选区、输入和关闭焦点，不增加 AI 导航', async ({ page }) => {
 await page.goto('/');
 const nav = page.getByRole('navigation', { name: '未命名的日常' });
 await expect(nav).toBeVisible();
 await expect(nav.getByRole('button', { name: 'Focal AI' })).toHaveCount(0);
 const open = page.getByRole('main').getByRole('button', { name: 'Focal AI' });
 await open.click();
 const drawer = page.getByRole('dialog', { name: 'Focal AI', exact: true });
 await expect(drawer.getByRole('textbox', { name: '选片消息' })).toBeFocused();
 await drawer.getByRole('textbox').fill('做一组克制、连贯的城市散步作品');
 await page.getByRole('button', { name: '查看第 2 张 交错的视线', exact: true }).click();
 await expect(drawer).toBeVisible();
 await expect(drawer.getByRole('textbox')).toHaveValue('做一组克制、连贯的城市散步作品');
 await drawer.getByRole('combobox', { name: '照片范围' }).selectOption('selected');
 await expect(drawer.getByRole('combobox', { name: '照片范围' })).toContainText('所选照片 · 1');
 await drawer.getByRole('button', { name: '选片设置' }).click();
 const settings = page.getByRole('dialog', { name: '设置', exact: true });
 await expect(settings.getByRole('combobox', { name: '每次最多分析照片' })).toBeVisible();
 await expect(settings.getByText('管理图像授权')).toHaveCount(0);
 await page.keyboard.press('Escape');
 await expect(settings).toHaveCount(0);
 await expect(drawer).toBeVisible();
 await mkdir(evidence, { recursive: true });
 await page.screenshot({ path: resolve(evidence, 'conversation.png') });
 await page.keyboard.press('Escape');
 await expect(drawer).toHaveCount(0);
 await expect(open).toBeFocused();
 await open.click();
 await expect(drawer.getByRole('textbox')).toHaveValue('做一组克制、连贯的城市散步作品');
 await page.getByRole('button', { name: '项目列表', exact: true }).click();
 await expect(drawer).toHaveCount(0);
});
